import json
import re
import sys

import markdown as md_lib
import weasyprint
from jinja2 import Environment
from markdown.extensions import Extension

env = Environment()

class _AsteriskOnlyEmphasis(Extension):

    # impedisce che il carattere underscore (_) venga interpretato come corsivo o grassetto
    def extendMarkdown(self, md):
        try:
            proc = md.inlinePatterns["em_strong"]
            proc.delimiters.pop("_", None)
            proc.tokens = [t for t in proc.tokens if t != "_"]
            proc.pattern = "|".join(re.escape(t) for t in proc.tokens)
            proc.compiled_re = re.compile(proc.pattern, re.DOTALL)
        except AttributeError as e:
            sys.stderr.write(
                f"ATTENZIONE: impossibile disattivare l'enfasi underscore "
                f"(struttura interna di 'markdown' diversa dal previsto): {e}\n"
            )


_MD = md_lib.Markdown(extensions=[_AsteriskOnlyEmphasis()])

BUILD_ID = "REP-2024-1187"

TEMPLATE_HEAD = """<html><head><meta charset="utf-8"><style>
body { font-family: sans-serif; margin: 40px; color: #222; }
h1 { color: #16425b; }
footer { font-size: 10px; color: #888; margin-top: 60px; border-top: 1px solid #ddd; padding-top: 8px; }
</style></head><body>
<h1>Mind Report</h1>
<div class="content">
"""

TEMPLATE_TAIL = """
</div>
<footer>Generated by ReportEngine v1.0 -- build {{ build_id }}</footer>
</body></html>
"""


def render(markdown_text: str) -> bytes:
    _MD.reset()
    body_html = _MD.convert(markdown_text or "")

    full_template_source = TEMPLATE_HEAD + body_html + TEMPLATE_TAIL

    template = env.from_string(full_template_source)
    rendered_html = template.render(build_id=BUILD_ID)

    return weasyprint.HTML(string=rendered_html).write_pdf()


def main():
    raw = sys.stdin.read()
    try:
        req = json.loads(raw)
        markdown_text = req.get("markdown", "")
    except json.JSONDecodeError as e:
        sys.stderr.write(f"Richiesta non valida: {e}\n")
        sys.exit(1)

    try:
        pdf_bytes = render(markdown_text)
    except Exception as e:
        sys.stderr.write(f"Errore durante il rendering: {type(e).__name__}: {e}\n")
        sys.exit(1)

    sys.stdout.buffer.write(pdf_bytes)
    sys.stdout.buffer.flush()
    sys.exit(0)


if __name__ == "__main__":
    main()
